let currentLanguage = 'es';

function initLanguage() {
    const langToggleBtn = document.getElementById('lang-toggle-btn');

    // Retrieve saved language or default to 'es'
    const savedLang = localStorage.getItem('airbnb_lang');
    if (savedLang && (savedLang === 'es' || savedLang === 'en')) {
        currentLanguage = savedLang;
    } else {
        const browserLang = navigator.language.substring(0, 2);
        if (browserLang === 'en') {
            currentLanguage = 'en';
        }
    }

    applyTranslations();

    if (langToggleBtn) {
        langToggleBtn.addEventListener('click', () => {
            currentLanguage = currentLanguage === 'es' ? 'en' : 'es';
            localStorage.setItem('airbnb_lang', currentLanguage);
            applyTranslations();
            
            // Dispatch dynamic event so maps.js and events.js can update
            const event = new CustomEvent('languageChanged', { detail: { lang: currentLanguage } });
            document.dispatchEvent(event);
        });
    }
}

function applyTranslations() {
    const dictionary = translationDictionary[currentLanguage];
    
    // Toggle label
    const langLabel = document.getElementById('lang-label');
    if (langLabel) {
        langLabel.textContent = currentLanguage === 'es' ? 'EN' : 'ES';
    }

    // Translate DOM elements
    for (const key in dictionary) {
        const element = document.getElementById(key);
        if (element) {
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                element.placeholder = dictionary[key];
            } else {
                element.innerHTML = dictionary[key];
            }
        }
    }

    // Set doc language tag
    document.documentElement.lang = currentLanguage;
}
